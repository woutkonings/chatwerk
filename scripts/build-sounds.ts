// Writes shared/sound-names.ts from the sample maps in web/public/sounds/*.json, so that
// the browser and the server know every loadable sample name without reading
// JSON at runtime. Run after a sample map changes: npx tsx scripts/build-sounds.ts
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const names = new Set<string>();
for (const file of readdirSync('web/public/sounds').filter((f) => f.endsWith('.json')).sort()) {
  const map = JSON.parse(readFileSync(`web/public/sounds/${file}`, 'utf8')) as Record<string, unknown>;
  for (const key of Object.keys(map)) if (!key.startsWith('_')) names.add(key);
}
const sorted = [...names].sort();
const lines = [
  '// Generated by scripts/build-sounds.ts from web/public/sounds/*.json. Do not edit.',
  'export const SAMPLE_NAMES: readonly string[] = [',
  ...sorted.map((name) => `  '${name}',`),
  '];',
  '',
];
writeFileSync('shared/sound-names.ts', lines.join('\n'));
console.log(`${sorted.length} sample names`);
